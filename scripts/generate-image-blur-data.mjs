/**
 * Build tiny JPEG blurDataURLs for hero portraits in /public.
 * Run after changing HeroSection/aligned/*.jpg:
 *   npm run generate:image-blur
 */
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const root = path.join(import.meta.dirname, "..");
const dir = path.join(root, "public", "HeroSection", "aligned");

async function main() {
  const map = {};
  for (let i = 1; i <= 8; i++) {
    const rel = `/HeroSection/aligned/${i}.jpg`;
    const file = path.join(dir, `${i}.jpg`);
    if (!fs.existsSync(file)) {
      console.warn("skip missing", file);
      continue;
    }
    const buf = await sharp(file)
      .resize(12, 18, { fit: "cover" })
      .blur(4)
      .jpeg({ quality: 40 })
      .toBuffer();
    map[rel] = `data:image/jpeg;base64,${buf.toString("base64")}`;
  }

  const fallbackBuf = await sharp({
    create: {
      width: 8,
      height: 8,
      channels: 3,
      background: { r: 20, g: 20, b: 22 },
    },
  })
    .jpeg({ quality: 50 })
    .toBuffer();

  const fallback = `data:image/jpeg;base64,${fallbackBuf.toString("base64")}`;

  const out = `// Generated by scripts/generate-image-blur-data.mjs — do not edit by hand.

export const HERO_PORTRAIT_BLUR: Record<string, string> = ${JSON.stringify(map, null, 2)};

/** Fallback when no per-image blur is available (dark, ~8px). */
export const IMAGE_BLUR_FALLBACK = ${JSON.stringify(fallback)};
`;

  const target = path.join(root, "lib", "image-blur-data.ts");
  fs.writeFileSync(target, out);
  console.log(`Wrote ${target} (${Object.keys(map).length} hero blurs)`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
